static int amzn_add_key_fdt(struct fireos_key *key, int parentoffset, void *fdt)
{
	int ret;
	int key_node;

	ret = fdt_add_subnode(fdt, parentoffset, key->key_name);

	if (ret < 0) {
		dprintf(CRITICAL, "Error in adding subnode %s\n", key->key_name);
		return ret;
	}

	ret = fdt_subnode_offset(fdt, parentoffset, key->key_name);

	if (ret < 0) {
		dprintf(CRITICAL, "Error in getting offset of %s", key->key_name);
		return ret;
	}

	key_node = ret;

	if ((ret = fdt_setprop(fdt, key_node, key->r_squared.name, key->r_squared.value, key->r_squared.len))	      ||
	     (ret = fdt_setprop(fdt, key_node, key->modulus.name, key->modulus.value, key->modulus.len))	      ||
	     (ret = fdt_setprop(fdt, key_node, key->exponent.name, key->exponent.value, key->exponent.len))	      ||
	     (ret = fdt_setprop(fdt, key_node, key->n0_inverse.name, key->n0_inverse.value, key->n0_inverse.len))     ||
	     (ret = fdt_setprop(fdt, key_node, key->num_bits.name, key->num_bits.value, key->num_bits.len))	      ||
	     (ret = fdt_setprop(fdt, key_node, key->required.name, key->required.value, strlen(key->required.value))) ||
	     (ret = fdt_setprop(fdt, key_node, key->algo.name, key->algo.value, strlen(key->algo.value)))	      ||
	     (ret = fdt_setprop(fdt, key_node, key->key_name_hint.name, key->key_name_hint.value, strlen(key->key_name_hint.value)))) {
		dprintf(CRITICAL, "Error in setting one of the properties for key %s\n", key->key_name);
		return ret;
	}
	return 0;
}

static int amzn_get_signature_offset(void *fdt)
{
	int ret = -1;
	int sig_offset;

	sig_offset = fdt_subnode_offset(fdt, 0, FIT_SIG_NODENAME);

	if (sig_offset >= 0) {
		dprintf(SPEW, "Found a signature node in DTB, will purge it\n");
		ret = fdt_del_node(fdt, sig_offset);
		if (ret < 0) {
			dprintf(CRITICAL, "Can't delete signature node\n");
			return ret;
		}
	}

	/* Create a fresh signature node */
	ret = fdt_add_subnode(fdt, 0, FIT_SIG_NODENAME);

	if (ret < 0) {
		dprintf(CRITICAL, "Can't create signature node for Amazon keys\n");
		return ret;
	}

	sig_offset = fdt_subnode_offset(fdt, 0, FIT_SIG_NODENAME);

	if (sig_offset < 0) {
		dprintf(CRITICAL, "Can't get offset for Amazon key node\n");
	}

	return sig_offset;
}

int amzn_setup_fit_keys(void *fdt)
{
	int ret = -1;
	int sig_node;

	ret = amzn_get_signature_offset(fdt);

	if (ret < 0) {
		dprintf(CRITICAL, "Error in getting offset of signature node");
		goto error;
	}

	sig_node = ret;

	ret = amzn_add_key_fdt(&fireos_key_list[FIREOS_KEY_PRODUCTION], sig_node, fdt);
	if (ret < 0) {
		dprintf(CRITICAL, "Error in adding production key to fdt");
		goto error;
	}

        if (AMZN_ENGINEERING_DEVICE  == amzn_target_device_type()) {
		ret = amzn_add_key_fdt(&fireos_key_list[FIREOS_KEY_ENGINEERING], sig_node, fdt);
		if (ret < 0) {
			dprintf(CRITICAL, "Error in adding engineering key to fdt");
			goto error;
		}
        }

	return 0;
error:
	dprintf(CRITICAL, ", error = %s\n", fdt_strerror(ret));
	return ret;
}
